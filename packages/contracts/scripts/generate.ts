// Generates openapi.yaml (OpenAPI 3.1), asyncapi.yaml (AsyncAPI 3.0) and openapi.ts (openapi-typescript types) from
// the Zod contracts in ../src. Usage: bun packages/contracts/scripts/generate.ts [outDir]   (default: ../generated)
import { mkdir, writeFile } from 'node:fs/promises'
import { join, resolve } from 'node:path'
import openapiTS, { astToString } from 'openapi-typescript'
import { stringify } from 'yaml'
import * as z from 'zod'
import {
  EVENT_SCHEMAS,
  EVENT_SUMMARIES,
  EVENT_TYPES,
  contractRegistry,
  operations,
  type EventType,
  type OperationSpec
} from '../src/index.ts'

type JsonSchema = Record<string, unknown>

const VERSION = '0.1.0'
const banner = '# Generated by packages/contracts/scripts/generate.ts from the Zod contracts. Do not edit.\n'

// Zod adds a long regex to every date and date-time string, and safe-integer bounds to every int. `format` and
// `type: integer` already say it, so drop them to keep the documents readable.
const override = ({ jsonSchema }: { jsonSchema: JsonSchema }) => {
  if (jsonSchema.format === 'date-time' || jsonSchema.format === 'date') delete jsonSchema.pattern
  if (jsonSchema.maximum === Number.MAX_SAFE_INTEGER) delete jsonSchema.maximum
  if (jsonSchema.minimum === Number.MIN_SAFE_INTEGER) delete jsonSchema.minimum
}

const toJsonSchema = (schema: z.ZodType, target: 'draft-2020-12' | 'draft-07'): JsonSchema => {
  const { $schema: _, ...rest } = z.toJSONSchema(schema, { target, override }) as JsonSchema
  return rest
}

const ref = (schema: z.ZodType) => {
  const meta = contractRegistry.get(schema)
  if (!meta) throw new Error('Request and response schemas must be registered with named()')
  return { $ref: `#/components/schemas/${meta.id}` }
}

const describeAccess = (op: OperationSpec) =>
  [
    op.roles === 'any' ? 'Roles: any.' : op.roles.length ? `Roles: ${op.roles.join(', ')}.` : 'People are refused.',
    op.agentScope ? `Agents need scope \`${op.agentScope}\`.` : 'Agents are refused.',
    op.events.length ? `Emits ${op.events.join(', ')}.` : ''
  ]
    .filter(Boolean)
    .join(' ')

const openApiOperation = (operationId: string, op: OperationSpec) => {
  const parameters: JsonSchema[] = []
  for (const [name, field] of Object.entries(op.params?.shape ?? {})) {
    parameters.push({ name, in: 'path', required: true, schema: toJsonSchema(field, 'draft-2020-12') })
  }
  for (const [name, field] of Object.entries(op.query?.shape ?? {})) {
    parameters.push({
      name,
      in: 'query',
      required: !(field instanceof z.ZodOptional),
      schema: toJsonSchema(field, 'draft-2020-12')
    })
  }
  if (op.method !== 'get') parameters.push({ $ref: '#/components/parameters/IdempotencyKey' })

  const content = op.stream
    ? { 'text/event-stream': { schema: { type: 'string' } } }
    : { 'application/json': { schema: ref(op.response) } }

  return {
    operationId,
    summary: op.summary,
    description: describeAccess(op),
    tags: [op.path.split('/')[1]],
    ...(parameters.length ? { parameters } : {}),
    ...(op.body ? { requestBody: { required: true, content: { 'application/json': { schema: ref(op.body) } } } } : {}),
    responses: {
      [op.status]: { description: op.summary, content },
      ...Object.fromEntries(
        Object.entries(op.responses ?? {}).map(([status, { description, schema }]) => [
          status,
          { description, content: { 'application/json': { schema: ref(schema) } } }
        ])
      ),
      ...(op.body || op.query ? { 400: { $ref: '#/components/responses/InvalidInput' } } : {}),
      401: { $ref: '#/components/responses/Unauthenticated' },
      403: { $ref: '#/components/responses/Denied' },
      ...(op.params ? { 404: { $ref: '#/components/responses/NotFound' } } : {})
    },
    'x-safe-edge-roles': op.roles,
    ...(op.agentScope ? { 'x-safe-edge-agent-scope': op.agentScope } : {}),
    'x-safe-edge-events': op.events
  }
}

const buildOpenApi = () => {
  const paths: Record<string, Record<string, unknown>> = {}
  for (const [operationId, op] of Object.entries(operations) as [string, OperationSpec][]) {
    if (op.handledBy === 'memory') continue
    paths[op.path] = { ...paths[op.path], [op.method]: openApiOperation(operationId, op) }
  }
  const { schemas } = z.toJSONSchema(contractRegistry, {
    target: 'draft-2020-12',
    override,
    uri: (id) => `#/components/schemas/${id}`
  }) as { schemas: Record<string, JsonSchema> }
  const errorResponse = (description: string, schema: string) => ({
    description,
    content: { 'application/json': { schema: { $ref: `#/components/schemas/${schema}` } } }
  })
  return {
    openapi: '3.1.0',
    info: {
      title: 'Safe Edge API',
      version: VERSION,
      description:
        'Safe Edge v1 REST API. Generated from the Zod contracts in packages/contracts. Every write accepts an ' +
        'Idempotency-Key header; a refused action returns 403 naming the policy rule. `x-safe-edge-roles` lists ' +
        'the roles allowed; `x-safe-edge-agent-scope` is the scope an agent token needs (absent: agents refused).'
    },
    servers: [{ url: '/v1', description: 'The API, or the in-browser demo transport' }],
    security: [{ bearer: [] }],
    paths,
    components: {
      securitySchemes: {
        bearer: { type: 'http', scheme: 'bearer', description: 'Opaque token that maps to an Actor' }
      },
      parameters: {
        IdempotencyKey: {
          name: 'Idempotency-Key',
          in: 'header',
          required: false,
          description: 'Replays the stored response for a repeated key; a different body with the same key is 422',
          schema: { type: 'string' }
        }
      },
      responses: {
        InvalidInput: errorResponse('The request failed validation', 'ApiError'),
        Unauthenticated: errorResponse('Missing or unknown bearer token', 'ApiError'),
        Denied: errorResponse('Refused by policy; `rule` names the rule', 'Denial'),
        NotFound: errorResponse('No record with that ID', 'ApiError')
      },
      schemas: Object.fromEntries(
        Object.entries(schemas).map(([id, { $schema: _s, $id: _i, ...schema }]) => [id, schema])
      )
    }
  }
}

// 'edge.work_order.drafted.v1' -> 'workOrderDrafted'
const messageKey = (type: EventType) =>
  type
    .replace(/^edge\.|\.v1$/g, '')
    .split(/[._]/)
    .map((word, i) => (i === 0 ? word : word[0]!.toUpperCase() + word.slice(1)))
    .join('')

const buildAsyncApi = () => {
  const keys = EVENT_TYPES.map(messageKey)
  return {
    asyncapi: '3.0.0',
    info: {
      title: 'Safe Edge events',
      version: VERSION,
      description:
        'CloudEvents 1.0 envelopes with source safe-edge://townships/{id} and subject segments/{id}. Payloads ' +
        'carry IDs and `simulated`, never images. Generated from the Zod contracts in packages/contracts.'
    },
    defaultContentType: 'application/cloudevents+json',
    channels: {
      edgeEvents: {
        address: '/v1/events',
        description: 'Server-sent events from GET /v1/events. Registered webhooks receive the same envelopes.',
        messages: Object.fromEntries(keys.map((key) => [key, { $ref: `#/components/messages/${key}` }]))
      }
    },
    operations: {
      publishEdgeEvents: {
        action: 'send',
        summary: 'The API publishes every domain event',
        channel: { $ref: '#/channels/edgeEvents' },
        messages: keys.map((key) => ({ $ref: `#/channels/edgeEvents/messages/${key}` }))
      }
    },
    components: {
      messages: Object.fromEntries(
        EVENT_TYPES.map((type) => [
          messageKey(type),
          {
            name: type,
            summary: EVENT_SUMMARIES[type],
            contentType: 'application/cloudevents+json',
            payload: toJsonSchema(EVENT_SCHEMAS[type], 'draft-07')
          }
        ])
      )
    }
  }
}

const yaml = (doc: unknown) => banner + stringify(doc, { lineWidth: 0, aliasDuplicateObjects: false })

const outDir = resolve(process.argv[2] ?? join(import.meta.dir, '../generated'))
const openApiYaml = yaml(buildOpenApi())
const types = astToString(await openapiTS(openApiYaml))
await mkdir(outDir, { recursive: true })
await writeFile(join(outDir, 'openapi.yaml'), openApiYaml)
await writeFile(join(outDir, 'asyncapi.yaml'), yaml(buildAsyncApi()))
await writeFile(join(outDir, 'openapi.ts'), `// ${banner.slice(2)}// openapi-typescript 7.13.0 output.\n\n${types}`)
console.log(`wrote openapi.yaml, asyncapi.yaml and openapi.ts to ${outDir}`)
